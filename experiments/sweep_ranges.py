#!/usr/bin/env python
"""Ranges across the Reynolds sweep, for the numbers the report quotes as spans.

report.tex summarises the v5 sweep as ranges ("63--79 %", "within 0.61 %",
"3.5--5.7 % high"). Each per-Re value is already in
runs/re_sweep_v5/summary.json; this reduces across Reynolds numbers, which a
single manifest source cannot do, and writes runs/re_sweep_v5/ranges.json.

    python experiments/sweep_ranges.py
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments"))
from derived_metrics import QU2013_TABLE3  # noqa: E402

SWEEP = ROOT / "runs" / "re_sweep_v5" / "summary.json"
OUT = ROOT / "runs" / "re_sweep_v5" / "ranges.json"


def main():
    sweep = json.loads(SWEEP.read_text())
    res = sorted(sweep, key=float)
    per_seed = {c: [sweep[r][f"{c}_shedding_s{s}"] for r in res for s in (0, 1)]
                for c in ("baseline", "all")}
    l2 = {c: [statistics.mean(sweep[r][f"{c}_rel_l2_s{s}"] for s in (0, 1)) for r in res]
          for c in ("baseline", "all")}
    st = [100.0 * (sweep[r]["St_vorticity"] / QU2013_TABLE3[r]["St"] - 1.0) for r in res]
    cd = [100.0 * (sweep[r]["Cd_mean"] / QU2013_TABLE3[r]["Cd"] - 1.0) for r in res]
    out = {
        "_about": "Generated by experiments/sweep_ranges.py from summary.json.",
        "Re": [float(r) for r in res],
        "baseline_shedding_min": min(per_seed["baseline"]),
        "baseline_shedding_max": max(per_seed["baseline"]),
        "all_shedding_min": min(per_seed["all"]),
        "all_shedding_max": max(per_seed["all"]),
        "baseline_rel_l2_mean": statistics.mean(l2["baseline"]),
        "all_rel_l2_min": min(l2["all"]),
        "all_rel_l2_max": max(l2["all"]),
        "St_vs_qu_pct": dict(zip(res, st)),
        "St_vs_qu_abs_max_pct": max(abs(v) for v in st),
        "Cd_vs_qu_pct": dict(zip(res, cd)),
        "Cd_vs_qu_min_pct": min(cd),
        "Cd_vs_qu_max_pct": max(cd),
    }
    OUT.write_text(json.dumps(out, indent=2) + "\n")
    for k, v in out.items():
        if k != "_about":
            print(f"{k:24s} {v}")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
